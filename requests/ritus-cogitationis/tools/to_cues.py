"""events.json (журнал прогона ritus.html) → cues.json для immollimma.
Метки разделов — стадии обряда; удары/акценты — сборка механизма, пуск, ересь, изгнание, ответ;
document — подписи на экране; отдельно — удары механизма (bell_beats) и механическое время (mt_curve)."""
import json, sys

src, dst = sys.argv[1], sys.argv[2]
d = json.load(open(src))
ev = d["events"]
MOOD = {
    "TENEBRAE": ("тьма, холодный кинескоп, гул", 0.05, "экран включается: точка → строка → кадр"),
    "INVOCATIO": ("литургия, призыв; механизм собирается из колец, ещё неподвижен", 0.35,
                  "четыре воззвания; от центра наружу встают кольца, 12 шестерён по одной, обод, спутники"),
    "UNCTIO": ("помазание, золотые волны масла по кольцам; благоговение", 0.4, "волны идут по кольцам изнутри наружу"),
    "EXCITATIO": ("пуск: первая попытка захлёбывается, вторая — разгон с перехлёстом", 0.6,
                  "27 — сила подаётся; 28.6–30 — глохнет; 30.6 «Iterum: surge!»; 33–38 — разгон"),
    "COGITATIO": ("вычисление: мерный механический ход, служба", 0.6, "счётчик молитв 0→8; удары механизма каждые 1,6 с"),
    "HAERESIS": ("скверна вползает: порча, сбой такта, пурпурный скрап-код", 0.85, "сектор пожирается 9 с, кольца сбиваются"),
    "EXORCISMUS": ("изгнание: волна от центра, литания, раскаление металла", 1.0, "4,5 с; к 71.5 сектор раскалён добела"),
    "COGITATIO RESUMPTA": ("служба продолжается; металл остывает; нарастание к ответу", 0.7, "молитвы 8→12"),
    "RESPONSUM": ("ответ машины: свет, торжество, но знание восстановлено лишь отчасти", 0.9,
                  "вспышка из сердца; «Responsum datum est»; RESTITUTUM 61% · LACUNAE III"),
    "QUIES": ("угасание: сила отводится, шестерни замедляются до остановки, кинескоп гаснет", 0.2,
              "88–95 замедление; детали гаснут снаружи внутрь; 97.3–99.6 выключение кинескопа"),
}
cues = []
stages = [e for e in ev if e["type"] == "stage"]
for i, e in enumerate(stages):
    end = stages[i + 1]["t"] if i + 1 < len(stages) else d["rite_len"]
    mood, inten, note = MOOD[e["name"]]
    cues.append(dict(t=e["t"], end=end, label=f'{e["num"]} {e["name"]}', kind="section", mood=mood, intensity=inten, note=note))

def add(t, label, kind, intensity=0.5, note="", end=None):
    c = dict(t=round(t, 4), label=label, kind=kind, intensity=intensity, note=note)
    if end is not None: c["end"] = end
    cues.append(c)

REVEAL_NAMES = {4.5: "сердце: линза загорается", 5.5: "кольцо I", 6.5: "кольцо II", 9.0: "кольцо III", 9.8: "кольцо IV",
                14.0: "кольцо V", 15.0: "кольцо VI", 16.0: "кольцо VII", 18.2: "обод"}
for e in ev:
    if e["type"] != "cue": continue
    t = e["t"]
    for s in e["captions"]:
        add(t, s, "document", 0.4, "подпись внизу экрана")
    if t in REVEAL_NAMES:
        add(t, REVEAL_NAMES[t], "hit" if t in (4.5, 18.2) else "accent", 0.5 if t != 18.2 else 0.7, "вспышка, деталь встаёт")
    elif 10.8 <= t <= 14.15 and e["flashes"]:
        add(t, "шестерня венца", "accent", 0.25, "12 шестерён по одной, через 0,3 с")
    elif 19 <= t <= 21.05 and e["flashes"]:
        add(t, "спутник", "accent", 0.35, "6 спутников, через 0,4 с")
add(0.0, "кинескоп включается", "accent", 0.3, "точка → строка (0–0.35) → кадр (до 1.2)")
add(22.3, "помазание: волны", "transition", 0.4, "волны масла по кольцам, 22.3–26.9", end=26.9)
add(27.0, "пуск: сила подана", "accent", 0.5, "механизм трогается (до 0.35 скорости)")
add(30.0, "механизм заглох", "silence", 0.1, "стоит до 33.0", end=30.6)
add(30.6, "Iterum: surge!", "hit", 0.8, "вспышка от центра, повторное воззвание")
add(33.2, "Vis motiva adest", "swell", 0.8, "разгон 33–38 до хода 1.0")
add(58.0, "ересь вторгается", "hit", 0.8, "скверна 58–67, нарастает")
add(67.0, "изгнание", "hit", 1.0, "волна изгнания 67–71.5; накал растёт")
add(71.5, "очищено: белый накал", "accent", 0.7, "накладка на ободе, остывание 14 с")
add(80.0, "ответ: вспышка", "hit", 1.0, "COGITATIO PERFECTA; удар механизма ровно здесь")
add(97.3, "кинескоп гаснет", "accent", 0.2, "кадр → строка → точка (до 99.6)")
add(99.6, "тишина до повтора", "silence", 0.0, "цикл повторяется с 0", end=d["rite_len"])
cues.sort(key=lambda c: (c["t"], c["kind"] != "section"))
out = dict(version=1, duration_s=d["rite_len"], fps=None, video="ritus.html (анимация, цикл 102 с)", cues=cues,
           bell_beats=[e["t"] for e in ev if e["type"] == "beat"],
           grid=dict(bpm=150, meter="4/4", bar_s=1.6, note="удары механизма в установившемся ходе — на кратных 1,6 с; все метки кратны 0,1 с (шестнадцатая)"),
           mt_curve=d["mt_curve"],
           loop=True)
json.dump(out, open(dst, "w"), ensure_ascii=False, indent=1)
print(len(cues), "меток")
